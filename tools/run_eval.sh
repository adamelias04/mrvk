#!/usr/bin/env bash
# Replay the compact derived bag through dynamic_obstacle_predictor alone (no
# Nav2, no RViz) and score the result with eval_predictor.py. Used to compare
# predictor variants on identical input.
#
# Usage: run_eval.sh <label> [duration_s] [rate] [extra ros args...]
set -e

LABEL=${1:-run}
DURATION=${2:-130}
RATE=${3:-3.0}
shift 3 2>/dev/null || true
BAG=${EVAL_BAG:-/home/adam/ws/rosbags/derived_jk0009}
OUT=/home/adam/ws/tools/results/${LABEL}.json

mkdir -p /home/adam/ws/tools/results

source /opt/ros/humble/setup.bash
source /home/adam/ws/install/setup.bash

# Pin the middleware: a shell left configured for the robot (zenoh client
# pointing at a router that is not on this network) makes every node fail or
# hang in rmw init, and the run dies with an unrelated-looking error.
export RMW_IMPLEMENTATION=rmw_fastrtps_cpp
unset ZENOH_CONFIG_OVERRIDE

pkill -f "dynamic_obstacle_predictor" 2>/dev/null || true
pkill -f "bag play $BAG" 2>/dev/null || true
sleep 1

ros2 run mrvk_gazebo dynamic_obstacle_predictor --ros-args \
  --params-file /home/adam/ws/src/mrvk_gazebo/config/predictor/dynamic_obstacle_predictor.yaml \
  -p use_sim_time:=true "$@" \
  > /tmp/eval_pred_${LABEL}.log 2>&1 &
PRED_PID=$!

sleep 3

# The recorded /clock is replayed as-is (not regenerated by the player) so the
# predictor and evaluator share exactly the timeline the segmentation saw.
ros2 bag play "$BAG" --disable-keyboard-controls --rate "$RATE" \
  > /tmp/eval_play_${LABEL}.log 2>&1 &
PLAY_PID=$!

python3 /home/adam/ws/tools/eval_predictor.py "$DURATION" "$OUT" \
  > /tmp/eval_out_${LABEL}.log 2>&1 || true

# `ros2 run` forks the actual node, so killing the wrapper PID leaves the
# node alive to contaminate the next run: match on the executable instead.
kill -INT $PLAY_PID $PRED_PID 2>/dev/null || true
sleep 2
kill -9 $PLAY_PID $PRED_PID 2>/dev/null || true
pkill -f "mrvk_gazebo/dynamic_obstacle_predictor" 2>/dev/null || true
pkill -f "bag play $BAG" 2>/dev/null || true

python3 - "$OUT" "$LABEL" <<'PY'
import json, sys
d = json.load(open(sys.argv[1]))
print(f"=== {sys.argv[2]} ===")
for k in ['seg_msgs','n_tracks_total','n_dynamic_tracks','n_judged_tracks',
          'n_false_positive_tracks','n_true_positive_tracks','n_middle_tracks',
          'n_unjudged_tracks','fp_frames','tp_frames','mid_frames',
          'unjudged_frames','total_dyn_frames','fp_rate']:
    print(f"{k:26s} {d.get(k)}")
PY
